def qmul(a, b):
    a0, a1, a2, a3 = a
    b0, b1, b2, b3 = b
    return (a0 * b0 - a1 * b1 - a2 * b2 - a3 * b3,
            a0 * b1 + a1 * b0 + a2 * b3 - a3 * b2,
            a0 * b2 - a1 * b3 + a2 * b0 + a3 * b1,
            a0 * b3 + a1 * b2 - a2 * b1 + a3 * b0)


def key(q):
    return tuple(int(round(x * 1e9)) for x in q)


def closure(gens):
    one = (1.0, 0.0, 0.0, 0.0)
    elems = {key(one): one}
    frontier = [one]
    while frontier:
        new = []
        for a in frontier:
            for g in gens:
                c = qmul(a, g)
                k = key(c)
                if k not in elems:
                    elems[k] = c
                    new.append(c)
        frontier = new
        if len(elems) > 1000:
            raise RuntimeError("group too large")
    return list(elems.values())


def cyc(n):  # cyclic group of order n inside the U(1) generated by i
    return closure([(math.cos(2 * math.pi / n), math.sin(2 * math.pi / n), 0.0, 0.0)])


