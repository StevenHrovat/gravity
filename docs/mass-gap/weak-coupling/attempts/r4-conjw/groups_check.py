def tables(G):
    idx = {key(g): i for i, g in enumerate(G)}
    n = len(G)
    mul = np.zeros((n, n), dtype=np.int64)
    for i, a in enumerate(G):
        for j, b in enumerate(G):
            mul[i, j] = idx[key(qmul(a, b))]
    one = idx[key((1.0, 0.0, 0.0, 0.0))]
    minus = idx[key((-1.0, 0.0, 0.0, 0.0))]
    inv = np.array([int(np.where(mul[i] == one)[0][0]) for i in range(n)])
    comm = mul[mul[mul[np.arange(n)[:, None], np.arange(n)[None, :]], inv[:, None]], inv[None, :]]
    # comm[a, b] = a b a^-1 b^-1
    return mul, inv, comm, one, minus


def class_reps(mul, inv, n):
    seen, reps = set(), []
    for x in range(n):
        if x in seen:
            continue
        reps.append(x)
        for g in range(n):
            seen.add(int(mul[mul[g, x], inv[g]]))
    return reps


def patterns(G):
    n = len(G)
    mul, inv, comm, one, minus = tables(G)
    achieved = set()
    count_flat2 = 0
    for x in class_reps(mul, inv, n):  # simultaneous conjugation preserves all six relations
        y = np.arange(n)[:, None, None]
        z = np.arange(n)[None, :, None]
        t = np.arange(n)[None, None, :]
        ok = [
            np.broadcast_to(comm[x, y] == minus, (n, n, n)),
            np.broadcast_to(comm[z, t] == minus, (n, n, n)),
            np.broadcast_to(comm[x, z] == one, (n, n, n)),
            np.broadcast_to(comm[x, t] == one, (n, n, n)),
            np.broadcast_to(comm[y, z] == one, (n, n, n)),
            np.broadcast_to(comm[y, t] == one, (n, n, n)),
        ]
        viol = np.zeros((n, n, n), dtype=np.int64)
        for b, arr in enumerate(ok):
            viol |= (~arr).astype(np.int64) << b
        achieved |= set(int(v) for v in np.unique(viol))
        count_flat2 += int((viol == 0).sum())
    minimal = [s for s in achieved if not any((o != s) and (o & s) == o for o in achieved)]
    named = sorted(sorted(REL[b] for b in range(6) if s >> b & 1) for s in minimal)
    return count_flat2, named, (mul, inv, comm, one, minus)


def centraliser_check(n, comm, one, minus):
    anti = np.argwhere(comm == minus)
    bad = []
    for a, b in anti:
        cen = np.where((comm[:, a] == one) & (comm[:, b] == one))[0]
        if len(cen) != 2:
            bad.append((int(a), int(b), int(len(cen))))
    return len(anti), bad


def mu_dijkstra(G, mul, one, minus):
    cost = [1.0 - g[0] for g in G]
    n = len(G)
    dist = [math.inf] * n
    length = [0] * n
    dist[one] = 0.0
    pq = [(0.0, 0, one)]
    while pq:
        d, k, u = heapq.heappop(pq)
        if d > dist[u] + 1e-12:
            continue
        for g in range(n):
            if g == one:
                continue
            v = int(mul[u, g])
            nd = d + cost[g]
            if nd < dist[v] - 1e-12 or (abs(nd - dist[v]) <= 1e-12 and k + 1 < length[v]):
                dist[v], length[v] = nd, k + 1
                heapq.heappush(pq, (nd, k + 1, v))
    return dist[minus], length[minus]


def u1_zero_mode(Nx, Ny, Nz, g2, nmax=2, grid=4096, W=30):
    M = Nx * Ny * Nz
    P = 2 * math.pi / Nz
    u = np.arange(grid) * (P / grid)
    K = np.zeros(grid)
    for w in range(-W, W + 1):
        K += np.exp(-(M / (2 * g2)) * (u + P * w) ** 2)
    lam = [float(np.sum(K * np.cos(Nz * n * u)) * (P / grid)) for n in range(nmax + 1)]
    out = []
    for n in range(1, nmax + 1):
        meas = -math.log(lam[n] / lam[0])
        pred = g2 * n * n * Nz / (2 * Nx * Ny)
        out.append({"n": n, "measured": meas, "predicted": pred, "rel_err": abs(meas - pred) / pred})
    return out


