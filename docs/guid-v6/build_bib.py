"""Build bibliography.tex for GUID v6: every key cited in the paper, in order of first citation, from the pools
bib-core.tex (version 5.1), bib-extra.tex and sections/*-bib.tex. Fails on a cited key that no pool defines.
An entry defined in several pools is taken from the first pool in the order core, extra, sections (alphabetical).
Run: python3 docs/guid-v6/build_bib.py"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def expand(path, seen=None):
    """The main file with every \\input inlined (preamble excluded), in reading order."""
    text = path.read_text()
    text = re.sub(r"(?<!\\)%.*", "", text)
    out = []
    pos = 0
    for m in re.finditer(r"\\input\{([^}]+)\}", text):
        out.append(text[pos:m.start()])
        name = m.group(1)
        pos = m.end()
        if name in ("preamble", "bibliography"):
            continue
        f = HERE / (name if name.endswith(".tex") else name + ".tex")
        if f.exists():
            out.append(expand(f))
    out.append(text[pos:])
    return "".join(out)


body = expand(HERE / "guid-v6.tex")
order = []
for m in re.finditer(r"\\cite(?:\[[^\]]*\])?\{([^}]+)\}", body):
    for k in m.group(1).split(","):
        k = k.strip()
        if k and k not in order:
            order.append(k)

pools = [HERE / "bib-core.tex", HERE / "bib-extra.tex"] + sorted((HERE / "sections").glob("*-bib.tex"))
entries, origin, dupes = {}, {}, []
for p in pools:
    text = re.sub(r"(?<!\\)%.*", "", p.read_text())
    parts = re.split(r"(?=\\bibitem\{)", text)
    for part in parts:
        m = re.match(r"\\bibitem\{([^}]+)\}", part)
        if not m:
            continue
        key = m.group(1).strip()
        if key in entries:
            dupes.append((key, origin[key].name, p.name))
            continue
        entries[key] = part.strip()
        origin[key] = p

missing = [k for k in order if k not in entries]
unused = sorted(k for k in entries if k not in order and origin[k].name != "bib-core.tex")
out = ["% Generated by build_bib.py from bib-core.tex, bib-extra.tex and sections/*-bib.tex; do not edit by hand.",
       "\\begin{thebibliography}{999}\\small"]
out += [entries[k] for k in order if k in entries]
out.append("\\end{thebibliography}")
(HERE / "bibliography.tex").write_text("\n".join(out) + "\n")
print(f"{len(order)} cited keys, {len(entries)} defined; written {len(order) - len(missing)} entries to bibliography.tex")
for d in dupes:
    print(f"duplicate key {d[0]}: kept {d[1]}, ignored {d[2]}")
for k in unused:
    print(f"defined but not cited: {k} ({origin[k].name})")
for k in missing:
    print(f"MISSING: {k}")
sys.exit(1 if missing else 0)
