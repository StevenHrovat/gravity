"""GRH bounds the length of a route: Bach's theorem (1990), under GRH for Dirichlet L-functions mod n:
  (a) the group (Z/nZ)^x is generated by the primes below 2 (ln n)^2;
  (b) every proper subgroup misses an element below 2 (ln n)^2; for prime p, the least quadratic non-residue is below
      2 (ln p)^2, so a compositeness witness for Miller's test is short.
This script checks (a) for every n from 3 to 20000 and (b) for the least quadratic non-residue for every prime below 200000,
and reports the worst ratio to the bound. A check, not a proof: GRH for Dirichlet L-functions is proved in Lean by others
(2026-11-20; external), which would make the bounds unconditional."""
import math


def primes_upto(m):
    s = bytearray([1]) * (m + 1)
    s[0:2] = b"\x00\x00"
    for i in range(2, int(m ** 0.5) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(s[i * i::i]))
    return [i for i in range(m + 1) if s[i]]


def units(n):
    return [a for a in range(1, n) if math.gcd(a, n) == 1]


def generated(n, gens):
    seen = {1}
    frontier = [1]
    while frontier:
        x = frontier.pop()
        for g in gens:
            y = x * g % n
            if y not in seen:
                seen.add(y)
                frontier.append(y)
    return len(seen)


P = primes_upto(200000)
worst_a = (0.0, None)
fail_a = []
for n in range(3, 20001):
    bound = 2 * math.log(n) ** 2
    gens = [p for p in P if p < bound and n % p != 0]
    need = len(units(n)) if n <= 3000 else None
    if need is None:
        # phi(n) by factorisation
        phi, m, q = n, n, 2
        while q * q <= m:
            if m % q == 0:
                phi -= phi // q
                while m % q == 0:
                    m //= q
            q += 1
        if m > 1:
            phi -= phi // m
        need = phi
    if generated(n, gens) != need:
        fail_a.append(n)
    # smallest prime bound that already generates
    k = 0
    for i in range(1, len(gens) + 1):
        if generated(n, gens[:i]) == need:
            k = gens[i - 1]
            break
    r = k / bound if k else 0.0
    if r > worst_a[0]:
        worst_a = (r, n)
print(f"(a) n = 3..20000: (Z/n)^x generated by primes < 2 ln^2 n: failures {fail_a[:10]} (count {len(fail_a)});"
      f" worst largest-needed-prime / bound = {worst_a[0]:.3f} at n = {worst_a[1]}")

worst_b = (0.0, None, None)
for p in P[1:]:
    a = 2
    while pow(a, (p - 1) // 2, p) == 1:
        a += 1
    r = a / (2 * math.log(p) ** 2)
    if r > worst_b[0]:
        worst_b = (r, p, a)
print(f"(b) primes 3..200000: least quadratic non-residue / 2 ln^2 p: worst {worst_b[0]:.3f} at p = {worst_b[1]}"
      f" (non-residue {worst_b[2]}); all below the bound: {worst_b[0] < 1}")
for N in (5, 11, 101, 1009, 10007):
    b = 2 * math.log(N) ** 2
    gens = [p for p in P if p < b and N % p != 0]
    print(f"    N = {N}: bound 2 ln^2 N = {b:.2f}; primes below it: {gens}; generate (Z/N)^x: "
          f"{generated(N, gens) == len(units(N))}")
